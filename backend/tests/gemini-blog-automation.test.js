import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import request from 'supertest';
import { MongoMemoryServer } from 'mongodb-memory-server';
import mongoose from 'mongoose';
import jwt from 'jsonwebtoken';
import bcrypt from 'bcryptjs';
import app from '../src/app.js';
import { Admin, Post, Setting } from '../src/models.js';
import { cleanupOldData } from '../src/cleanup.js';
import {
  generateFallbackCoverSvg,
  getRealisticFallbackCover,
  REALISTIC_CYBER_COVERS,
  getGeminiApiKey,
} from '../src/services/geminiBlog.js';

const TEST_SECRET = 'super_secure_jwt_secret_for_testing_purposes_only_32chars';
process.env.JWT_SECRET = TEST_SECRET;

let mongod;
let ownerToken;

beforeAll(async () => {
  mongod = await MongoMemoryServer.create();
  await mongoose.connect(mongod.getUri());

  const hashedPw = await bcrypt.hash('Secret123!', 10);
  const owner = await Admin.create({ email: 'owner@blog.internal', password: hashedPw, role: 'owner' });
  ownerToken = jwt.sign({ id: owner._id, email: owner.email, role: 'owner' }, TEST_SECRET, { expiresIn: '1h' });
});

afterAll(async () => {
  await mongoose.disconnect();
  await mongod.stop();
});

describe('Gemini AI Blog Automation & 7-Day MongoDB Cleanup', () => {
  it('generates high-tech fallback SVG cover with title and category', () => {
    const svgData = generateFallbackCoverSvg('How Temp Mail Stops Phishing', 'CYBERSECURITY');
    expect(svgData).toContain('data:image/svg+xml;utf8,');
    expect(svgData).toContain('How%20Temp%20Mail%20Stops%20Phishing');
    expect(svgData).toContain('CYBERSECURITY');
  });

  it('provides high-resolution photorealistic cybersecurity cover photography', () => {
    const photoUrl = getRealisticFallbackCover('Advanced Phishing Attacks in 2026');
    expect(photoUrl).toBeDefined();
    expect(photoUrl).toContain('https://images.unsplash.com/');
    expect(REALISTIC_CYBER_COVERS).toContain(photoUrl);
  });

  it('resolves Gemini API key from MongoDB setting or environment variable', async () => {
    // When empty
    delete process.env.GEMINI_API_KEY;
    await Setting.deleteOne({ key: 'geminiApiKey' });
    expect(await getGeminiApiKey()).toBe('');

    // When in env
    process.env.GEMINI_API_KEY = 'env_test_gemini_key_123';
    expect(await getGeminiApiKey()).toBe('env_test_gemini_key_123');

    // When in database, database takes precedence
    await Setting.updateOne({ key: 'geminiApiKey' }, { value: 'db_test_gemini_key_456' }, { upsert: true });
    expect(await getGeminiApiKey()).toBe('db_test_gemini_key_456');

    // Clean up
    await Setting.deleteOne({ key: 'geminiApiKey' });
    delete process.env.GEMINI_API_KEY;
  });

  it('updates Gemini blog settings via admin PUT /api/admin/settings', async () => {
    const res = await request(app)
      .put('/api/admin/settings')
      .set('Authorization', `Bearer ${ownerToken}`)
      .send({
        ttlMinutes: 30,
        maxMessageKB: 2048,
        geminiApiKey: 'AIzaSyTestKeyFromAdminSettings',
        geminiAutoBlogEnabled: true,
        geminiAutoBlogIntervalHours: 24,
        geminiModel: 'gemini-3.8-flash',
      });

    expect(res.status).toBe(200);
    expect(res.body.geminiApiKey).toBe('AIzaSyTestKeyFromAdminSettings');
    expect(res.body.geminiAutoBlogEnabled).toBe(true);
    expect(res.body.geminiAutoBlogIntervalHours).toBe(24);
  });

  it('returns AI status from GET /api/admin/blog/ai-status', async () => {
    const res = await request(app)
      .get('/api/admin/blog/ai-status')
      .set('Authorization', `Bearer ${ownerToken}`);

    expect(res.status).toBe(200);
    expect(res.body.hasKey).toBe(true);
    expect(res.body.keySource).toBe('database');
    expect(res.body.maskedKey).toContain('AIza...ings');
    expect(res.body.enabled).toBe(true);
    expect(res.body.intervalHours).toBe(24);
  });

  it('automatically purges 7-day-old AI blog posts from MongoDB and counts them', async () => {
    const tenDaysAgo = new Date(Date.now() - 10 * 24 * 60 * 60 * 1000);
    const threeDaysAgo = new Date(Date.now() - 3 * 24 * 60 * 60 * 1000);
    const inSevenDays = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000);

    // 1. Create a manual post older than 10 days (should NOT be deleted!)
    const manualOldPost = await Post.create({
      title: 'Manual Old Guide to Privacy',
      slug: 'manual-old-guide-to-privacy',
      body: 'This is a permanent article created manually by admin.',
      author: 'Admin Team',
      published: true,
      isAutoGenerated: false,
      createdAt: tenDaysAgo,
    });

    // 2. Create an expired AI blog post (should BE DELETED!)
    const expiredAiPost = await Post.create({
      title: 'Expired AI Article 10 Days Old',
      slug: 'expired-ai-article-10-days-old',
      body: 'Temporary research article that has passed 7 days.',
      author: 'TempMail AI Research',
      published: true,
      isAutoGenerated: true,
      coverImage: generateFallbackCoverSvg('Expired AI Article'),
      expiresAt: threeDaysAgo, // expired 3 days ago
      createdAt: tenDaysAgo,
    });

    // 3. Create a fresh AI blog post (should NOT be deleted!)
    const freshAiPost = await Post.create({
      title: 'Fresh AI Article Created Today',
      slug: 'fresh-ai-article-created-today',
      body: 'Brand new research article with 7 days remaining.',
      author: 'TempMail AI Research',
      published: true,
      isAutoGenerated: true,
      coverImage: generateFallbackCoverSvg('Fresh AI Article'),
      expiresAt: inSevenDays,
      createdAt: new Date(),
    });

    // Execute 7-day retention cleanup
    const summary = await cleanupOldData(7);

    expect(summary.autoBlogPostsDeleted).toBeGreaterThanOrEqual(1);
    expect(summary.totalDeleted).toBeGreaterThanOrEqual(1);

    // Verify manual post still exists in MongoDB
    const manualFound = await Post.findById(manualOldPost._id);
    expect(manualFound).not.toBeNull();
    expect(manualFound.title).toBe('Manual Old Guide to Privacy');

    // Verify expired AI post is DELETED from MongoDB
    const expiredFound = await Post.findById(expiredAiPost._id);
    expect(expiredFound).toBeNull();

    // Verify fresh AI post still exists in MongoDB
    const freshFound = await Post.findById(freshAiPost._id);
    expect(freshFound).not.toBeNull();
    expect(freshFound.title).toBe('Fresh AI Article Created Today');

    // Verify Setting 'lastDataCleanup' contains the count
    const lastCleanup = (await Setting.findOne({ key: 'lastDataCleanup' })).value;
    expect(lastCleanup.autoBlogPostsDeleted).toBeGreaterThanOrEqual(1);
    expect(lastCleanup.totalDeleted).toBeGreaterThanOrEqual(1);
  });

  it('serves coverImage and auto-generated metadata on public GET /api/posts', async () => {
    const res = await request(app).get('/api/posts');
    expect(res.status).toBe(200);
    expect(Array.isArray(res.body.posts)).toBe(true);

    const freshPost = res.body.posts.find((p) => p.slug === 'fresh-ai-article-created-today');
    expect(freshPost).toBeDefined();
    expect(freshPost.isAutoGenerated).toBe(true);
    expect(freshPost.coverImage).toContain('data:image/svg+xml');
    expect(freshPost.expiresAt).toBeDefined();
  });
});
