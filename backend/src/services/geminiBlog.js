/**
 * Automates content research, article synthesis, and image generation using Google Gemini.
 * Saves the article to MongoDB with isAutoGenerated: true and a 7-day expiration date.
 */
export async function generateBlogPostWithGemini({ customTopic, author = 'TempMail AI Security Analyst' } = {}) {
  const apiKey = await getGeminiApiKey();
  if (!apiKey) {
    throw new Error('Gemini API key is not configured. Please set GEMINI_API_KEY in .env or configure it in Admin Settings.');
  }

  const settings = await getSettings();
  const configuredTextModel = settings.geminiModel || 'gemini-3.8-flash';
  const configuredImageModel = settings.geminiImageModel || 'gemini-nano-banana-2.1';

  // Candidate models in priority order for resilience against 503 high-demand spikes
  const candidateTextModels = [
    configuredTextModel,
    'gemini-3.5-flash-lite',
    'gemini-2.5-flash',
    'gemini-2.0-flash',
    'gemini-1.5-flash',
  ].filter((m, idx, arr) => m && arr.indexOf(m) === idx);

  // Choose topic
  const topic = customTopic || DEFAULT_BLOG_TOPICS[Math.floor(Math.random() * DEFAULT_BLOG_TOPICS.length)];

  const ai = new GoogleGenAI({ apiKey });

  const prompt = `You are an elite cybersecurity researcher and privacy advocate writing for the TempMail blog.

Conduct research and write a comprehensive, authoritative, engaging blog post about: "${topic}".

Your response MUST be ONLY valid JSON matching this schema exactly (without markdown code blocks or additional text):
{
  "title": "Clear, captivating, SEO-friendly headline (50-75 characters)",
  "slug": "unique-kebab-case-slug-based-on-title",
  "metaDescription": "Concise summary for search engines and social cards (130-160 characters)",
  "tags": ["Privacy", "Security", "TempMail", "Cybersecurity", "IdentityProtection"],
  "imagePrompt": "Detailed visual prompt for generating a sleek 3D illustration or minimalist cyber security digital art representing this concept. Teal and slate theme, clean geometric lines, no readable letters or text on image.",
  "body": "Detailed article in Markdown format. Include an introduction explaining why this matters now, 3-4 structured sections with H2 and H3 headings, actionable privacy tips, bullet points, real-world examples, and a conclusion on using temporary email to stay safe."
}`;

  let articleData = null;
  let lastTextError = null;

  for (const modelToTry of candidateTextModels) {
    try {
      console.log(`[Gemini Blog] Attempting content research using model "${modelToTry}"...`);
      const interaction = await ai.interactions.create({
        model: modelToTry,
        input: prompt,
      });

      const rawText = (interaction.output_text || '').trim();
      const cleanJson = rawText
        .replace(/^```json\s*/i, '')
        .replace(/^```\s*/i, '')
        .replace(/\s*```$/i, '')
        .trim();

      articleData = JSON.parse(cleanJson);
      if (articleData?.title && articleData?.body) {
        console.log(`[Gemini Blog] Successfully generated article with model "${modelToTry}".`);
        break;
      }
    } catch (err) {
      console.warn(`[Gemini Blog] Model "${modelToTry}" error: ${err.message}. Trying next fallback model...`);
      lastTextError = err;
      await new Promise((r) => setTimeout(r, 600));
    }
  }

  if (!articleData || !articleData.title || !articleData.body) {
    throw new Error(`Failed to generate article from Gemini: ${lastTextError?.message || 'Empty response'}`);
  }

  // Ensure unique slug
  let slug = String(articleData.slug || articleData.title)
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  if (!slug) slug = `post-${Date.now()}`;

  const existing = await Post.findOne({ slug });
  if (existing) {
    slug = `${slug}-${Date.now().toString().slice(-4)}`;
  }

  // Attempt image generation with Gemini, with candidate fallbacks
  let coverImage = '';
  const candidateImageModels = [
    configuredImageModel,
    'gemini-nano-banana-2.1',
    'gemini-3.1-flash-lite-image',
  ].filter((m, idx, arr) => m && arr.indexOf(m) === idx);

  for (const imgModel of candidateImageModels) {
    try {
      const imgPrompt =
        articleData.imagePrompt ||
        `Modern high-tech 3D cybersecurity concept art for ${articleData.title}, glowing teal and dark slate, minimalist, no text`;

      const imgInteraction = await ai.interactions.create({
        model: imgModel,
        input: imgPrompt,
      });

      if (imgInteraction.output_image?.data) {
        const mime = imgInteraction.output_image.mime_type || 'image/png';
        coverImage = `data:${mime};base64,${imgInteraction.output_image.data}`;
        break;
      }
    } catch (imgErr) {
      console.warn(`[Gemini Blog] Image model "${imgModel}" note (${imgErr.message}).`);
    }
  }

  // If no coverImage from API, ensure we have the vector cover
  if (!coverImage) {
    coverImage = generateFallbackCoverSvg(articleData.title, articleData.tags?.[0] || 'Security');
  }

  // Calculate 7-day retention expiration date
  const now = new Date();
  const expiresAt = new Date(now.getTime() + 7 * 24 * 60 * 60 * 1000);

  const post = await Post.create({
    title: articleData.title,
    slug,
    body: articleData.body,
    metaDescription: articleData.metaDescription || '',
    published: true,
    author,
    coverImage,
    tags: Array.isArray(articleData.tags) ? articleData.tags : ['Privacy', 'Cybersecurity'],
    isAutoGenerated: true,
    expiresAt,
  });

  // Update last run timestamp in MongoDB settings
  await Setting.updateOne(
    { key: 'lastAutoBlogRun' },
    { value: new Date().toISOString() },
    { upsert: true }
  );

  return post;
}

/**
 * Background scheduler that runs every hour to check if 24 hours have passed since last auto blog run.
 */
let schedulerInterval = null;

export function startGeminiBlogScheduler() {
  if (schedulerInterval) return;

  const checkAndRun = async () => {
    try {
      const settings = await getSettings();
      if (settings.geminiAutoBlogEnabled === false) return;

      const apiKey = await getGeminiApiKey();
      if (!apiKey) return; // Silent if no key is configured yet

      const lastRun = settings.lastAutoBlogRun ? new Date(settings.lastAutoBlogRun) : null;
      const intervalMs = (Number(settings.geminiAutoBlogIntervalHours) || 24) * 60 * 60 * 1000;
      const now = Date.now();

      // Check if interval elapsed or if zero posts exist
      const postsCount = await Post.countDocuments();
      const shouldRun = !lastRun || now - lastRun.getTime() >= intervalMs || postsCount === 0;

      if (shouldRun) {
        console.log('[Gemini Blog Scheduler] Starting automated 24-hour blog research and publication...');
        const newPost = await generateBlogPostWithGemini();
        console.log(`[Gemini Blog Scheduler] Successfully published AI post: "${newPost.title}" (${newPost.slug})`);
      }
    } catch (err) {
      console.error('[Gemini Blog Scheduler] Automatic run encountered an error:', err.message);
    }
  };

  // Initial check 10 seconds after server boot
  setTimeout(checkAndRun, 10000);

  // Periodic hourly check
  schedulerInterval = setInterval(checkAndRun, 60 * 60 * 1000);
}

export function stopGeminiBlogScheduler() {
  if (schedulerInterval) {
    clearInterval(schedulerInterval);
    schedulerInterval = null;
  }
}
